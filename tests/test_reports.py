def test_date_range_calculations():
    """Verify start and end datetime bounds for different period presets."""
    service = ReportService()
    
    # Today
    s_today, e_today = service.calculate_date_range("today")
    assert s_today is not None
    assert e_today is not None
    assert s_today.date() == e_today.date()

    # Week
    s_week, e_week = service.calculate_date_range("week")
    assert s_week <= e_week

    # Month
    s_month, e_month = service.calculate_date_range("month")
    assert s_month.day == 1

    # Year
    s_year, e_year = service.calculate_date_range("year")
    assert s_year.month == 1
    assert s_year.day == 1

    # Custom
    s_cust, e_cust = service.calculate_date_range("custom", "2026-01-01", "2026-01-31")
    assert s_cust.year == 2026
    assert s_cust.month == 1
    assert s_cust.day == 1
    assert e_cust.day == 31


def test_report_service_aggregation(app):
    """Verify aggregated metrics and category breakdown generated by ReportService."""
    with app.app_context():
        reg_repo = RegistrationRepository()
        prayer_repo = PrayerRequestRepository()

        reg_repo.create({"name": "Vol 1", "email": "v1@test.com", "registration_type": "volunteer", "status": "approved"})
        reg_repo.create({"name": "Vol 2", "email": "v2@test.com", "registration_type": "volunteer", "status": "new"})
        reg_repo.create({"name": "Part 1", "organization_name": "Org 1", "email": "p1@test.com", "registration_type": "partner", "status": "contacted"})

        prayer_repo.create({"category": "Health & Healing", "request_text": "Prayer 1", "status": "new"})
        prayer_repo.create({"category": "Health & Healing", "request_text": "Prayer 2", "status": "praying"})
        prayer_repo.create({"category": "Family & Relationships", "request_text": "Prayer 3", "status": "completed"})

        service = ReportService()
        rep = service.generate_report(period="all")

        assert rep["registrations"]["total"] == 3
        assert rep["registrations"]["volunteers"] == 2
        assert rep["registrations"]["partners"] == 1
        assert rep["registrations"]["approved"] == 1
        assert rep["registrations"]["contacted"] == 1

        assert rep["prayer_requests"]["total"] == 3
        assert rep["prayer_requests"]["praying"] == 1
        assert rep["prayer_requests"]["completed"] == 1

        # Check category breakdown
        cats = {item["category"]: item["count"] for item in rep["prayer_categories"]}
        assert cats["Health & Healing"] == 2
        assert cats["Family & Relationships"] == 1


def test_reports_http_view(client, app):
    """Test accessing reports via HTTP."""
    with app.app_context():
        auth = AuthService()
        auth.create_admin_user("report_user@test.org", "Password123!", "Report Admin", "Admin")

    client.post("/admin/auth/login", data={"email": "report_user@test.org", "password": "Password123!"})
